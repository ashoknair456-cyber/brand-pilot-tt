
import React, { useState, useContext, useEffect } from 'react';
import { BrandContext } from '../contexts/BrandContext';
import { generateMultiChannelCampaign, calculateConsistencyScore, performMarketResearch, generateCampaignImage, editCampaignImage, translateContent, ResearchResult } from '../services/geminiService';
import { GeneratedChannelContent } from '../types';
import { Send as SendIcon, Loader2, Sparkles, Copy, Instagram, Linkedin, Twitter, Mail, Megaphone, Check, CheckCircle2, Globe, Image as ImageIcon, Wand2, RefreshCw, Share2, Facebook, MonitorPlay, MessageCircle, Send, Languages, Calendar } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useAuth } from '../contexts/AuthContext';


const Generator: React.FC = () => {
  const { brand, addCampaign, settings } = useContext(BrandContext);
  const { user } = useAuth();
  const navigate = useNavigate();

  const [objective, setObjective] = useState('');
  const [audienceOverride, setAudienceOverride] = useState('');
  const [useSearch, setUseSearch] = useState(false);
  const [researchResult, setResearchResult] = useState<ResearchResult | null>(null);

  const [isGenerating, setIsGenerating] = useState(false);
  const [channels, setChannels] = useState<GeneratedChannelContent[] | null>(null);
  const [activeTab, setActiveTab] = useState(0);
  const [consistencyScore, setConsistencyScore] = useState<number | null>(null);

  // Image Gen State
  const [imageRatio, setImageRatio] = useState("1:1");
  const [imageSize, setImageSize] = useState("1K");
  const [imageStyle, setImageStyle] = useState("Photorealistic");
  const [isThumbnailMode, setIsThumbnailMode] = useState(false);
  const [isGeneratingImage, setIsGeneratingImage] = useState(false);
  const [isEditingImage, setIsEditingImage] = useState(false);
  const [editPrompt, setEditPrompt] = useState('');
  const [customImagePrompt, setCustomImagePrompt] = useState('');

  // Translation & Scheduling State
  const [targetLang, setTargetLang] = useState('English');
  const [isTranslating, setIsTranslating] = useState(false);
  const [scheduledDate, setScheduledDate] = useState('');

  const [copied, setCopied] = useState(false);
  const [pushed, setPushed] = useState(false);
  const [pushLoading, setPushLoading] = useState(false);

  useEffect(() => {
    if (channels && channels[activeTab]) {
      const ch = channels[activeTab];
      setCustomImagePrompt(ch.imagePrompt || (ch.headline ? `Editorial photo for: ${ch.headline}` : `Image representing: ${ch.content.slice(0, 100)}`));

      switch (ch.platform) {
        case 'instagram': setImageRatio("1:1"); break;
        case 'twitter':
        case 'facebook':
        case 'linkedin':
        case 'blog': setImageRatio("16:9"); break;
        case 'email': setImageRatio("4:3"); break;
        default: setImageRatio("16:9");
      }
      setIsThumbnailMode(false);
    }
  }, [activeTab, channels]);

  const handleGenerate = async () => {
    if (!objective) return;
    if (!brand.name) {
      alert("Please configure your Brand DNA first.");
      navigate('/brand-dna');
      return;
    }

    setIsGenerating(true);
    setChannels(null);
    setConsistencyScore(null);
    setResearchResult(null);
    setActiveTab(0);
    setCopied(false);
    setPushed(false);
    setScheduledDate(''); // Reset scheduling
    setTargetLang('English');

    try {
      let researchDataString = '';
      if (useSearch) {
        const research = await performMarketResearch(objective);
        setResearchResult(research);
        researchDataString = research.text;
      }

      const generatedChannels = await generateMultiChannelCampaign(brand, objective, audienceOverride, researchDataString);
      setChannels(generatedChannels);

      const score = await calculateConsistencyScore(generatedChannels, brand);
      setConsistencyScore(score);

      addCampaign({
        id: Date.now().toString(),
        name: objective.length > 50 ? objective.slice(0, 50) + '...' : objective,
        objective,
        status: 'generated',
        language: 'English',
        channels: generatedChannels,
        createdAt: new Date().toISOString(),
        metrics: {
          predictedEngagement: Math.floor(Math.random() * 40) + 60,
          consistencyScore: score
        }
      });

      // AUTO-GENERATE IMAGE (INTEGRATION UPDATE)
      // The user requested: "integrate... to generate the image according to the input data"
      // We automatically trigger image generation for the first channel with a prompt (usually Instagram).
      const targetChannel = generatedChannels.find(c => c.platform === 'instagram') || generatedChannels[0];

      if (targetChannel) {
        setIsGeneratingImage(true);
        // Use the prompt generated by the text model OR fallback to the Campaign Title (objective)
        const autoPrompt = targetChannel.imagePrompt || objective;
        console.log(`Auto-generating image with prompt (${targetChannel.imagePrompt ? 'From AI' : 'From Title'}):`, autoPrompt);

        try {
          // We use the default settings (1:1, 1K, Photorealistic) or infer from context if possible
          const base64 = await generateCampaignImage(autoPrompt, "1:1", "1K", "Photorealistic");

          // Update state
          setChannels(prev => {
            if (!prev) return null;
            return prev.map(c => {
              if (c.platform === targetChannel.platform) {
                return { ...c, generatedImage: base64 };
              }
              return c;
            });
          });
        } catch (imgError) {
          console.error("Auto-generation of image failed:", imgError);
          // We don't alert here to avoid disrupting the flow, user can try manually
        } finally {
          setIsGeneratingImage(false);
        }
      }

    } catch (error) {
      alert("Failed to generate content. Please check connection.");
      console.error(error);
    } finally {
      setIsGenerating(false);
    }
  };

  const handleTranslate = async () => {
    if (!channels || targetLang === 'English') return;
    setIsTranslating(true);

    try {
      const currentContent = channels[activeTab].content;
      const translated = await translateContent(currentContent, targetLang, brand.tone);

      const updatedChannels = [...channels];
      updatedChannels[activeTab] = {
        ...updatedChannels[activeTab],
        content: translated
      };
      setChannels(updatedChannels);
    } catch (e) {
      alert("Translation failed");
    } finally {
      setIsTranslating(false);
    }
  };

  const handleTabChange = (idx: number) => {
    setActiveTab(idx);
    setCopied(false);
    // Reset translation state when switching tabs to avoid confusion
    setTargetLang('English');
  };

  const handleGenerateImage = async (prompt: string) => {
    setIsGeneratingImage(true);
    try {
      let finalPrompt = prompt;
      if (isThumbnailMode) {
        finalPrompt = `YouTube/Social Link Thumbnail: ${prompt}. High contrast, vibrant, eye-catching, designed for small screens, clear focal point.`;
      }

      const base64 = await generateCampaignImage(finalPrompt, imageRatio, imageSize, imageStyle);
      if (channels) {
        const updatedChannels = [...channels];
        updatedChannels[activeTab] = {
          ...updatedChannels[activeTab],
          generatedImage: base64
        };
        setChannels(updatedChannels);
      }
    } catch (e) {
      console.error(e);
      alert("Failed to generate image.");
    } finally {
      setIsGeneratingImage(false);
    }
  };

  const handleEditImage = async () => {
    if (!channels || !channels[activeTab].generatedImage || !editPrompt) return;
    setIsEditingImage(true);
    try {
      const base64 = await editCampaignImage(channels[activeTab].generatedImage!, editPrompt);
      const updatedChannels = [...channels];
      updatedChannels[activeTab] = {
        ...updatedChannels[activeTab],
        generatedImage: base64
      };
      setChannels(updatedChannels);
      setEditPrompt('');
    } catch (e) {
      console.error(e);
      alert("Failed to edit image.");
    } finally {
      setIsEditingImage(false);
    }
  };

  const handleCopy = () => {
    if (channels) {
      const text = channels[activeTab].headline
        ? `${channels[activeTab].headline}\n\n${channels[activeTab].content}`
        : channels[activeTab].content;

      navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleShare = (platform: string) => {
    if (!channels) return;
    const currentChannel = channels[activeTab];
    const text = encodeURIComponent(currentChannel.content);
    const url = encodeURIComponent(window.location.href);

    let shareUrl = '';
    switch (platform) {
      case 'twitter':
        shareUrl = `https://twitter.com/intent/tweet?text=${text}`;
        break;
      case 'facebook':
        shareUrl = `https://www.facebook.com/sharer/sharer.php?u=${url}&quote=${text}`;
        break;
      case 'linkedin':
        handleCopy();
        shareUrl = `https://www.linkedin.com/sharing/share-offsite/?url=${url}`;
        alert("Content copied to clipboard! Paste it into your LinkedIn post.");
        break;
      case 'whatsapp':
        shareUrl = `https://wa.me/?text=${text}%20${url}`;
        break;
      case 'telegram':
        shareUrl = `https://t.me/share/url?url=${url}&text=${text}`;
        break;
      case 'email':
        const subject = encodeURIComponent(currentChannel.headline || "New Campaign Draft");
        shareUrl = `mailto:?subject=${subject}&body=${text}`;
        break;
    }

    if (shareUrl) {
      window.open(shareUrl, '_blank', 'width=600,height=400');
    }
  };

  const handlePush = async () => {
    if (!settings.enableN8n && !settings.enableZapier) {
      if (confirm("Automation is not configured. Go to Settings?")) {
        navigate('/settings');
      }
      return;
    }

    setPushLoading(true);

    const payload = {
      campaign_name: objective,
      brand_name: brand.name,
      channels: channels,
      language: targetLang,
      timestamp: new Date().toISOString(),
      scheduling: {
        is_scheduled: !!scheduledDate,
        scheduled_date: scheduledDate || null
      },
      user_email: user?.email || "anonymous@brandpilot.ai",
      meta: {
        score: consistencyScore,
        research: researchResult ? true : false
      }
    };

    try {
      const promises = [];
      if (settings.enableN8n && settings.n8nWebhookUrl) {
        promises.push(
          fetch(settings.n8nWebhookUrl, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(payload)
          })
        );
      }
      if (settings.enableZapier && settings.zapierWebhookUrl) {
        promises.push(
          fetch(settings.zapierWebhookUrl, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(payload)
          })
        );
      }

      const responses = await Promise.all(promises);
      const failed = responses.find(r => !r.ok);
      if (failed) {
        throw new Error(`Webhook failed with status ${failed.status}`);
      }
      setPushed(true);
      alert(`Campaign successfully pushed to automation! ${scheduledDate ? `(Scheduled for ${new Date(scheduledDate).toLocaleString()})` : ''}`);
    } catch (e: any) {
      console.error(e);
      alert(e.message || "Push failed. Check console for CORS or network errors.");
    } finally {
      setPushLoading(false);
    }
  };

  const getIcon = (platform: string) => {
    switch (platform) {
      case 'instagram': return <Instagram className="w-4 h-4" />;
      case 'linkedin': return <Linkedin className="w-4 h-4" />;
      case 'twitter': return <Twitter className="w-4 h-4" />;
      case 'facebook': return <Facebook className="w-4 h-4" />;
      case 'email': return <Mail className="w-4 h-4" />;
      default: return <Megaphone className="w-4 h-4" />;
    }
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 h-[calc(100vh-8rem)]">

      {/* Input Chamber */}
      <div className="lg:col-span-4 glass-panel p-8 rounded-2xl border-t border-cyan-500/20 flex flex-col gap-6 h-full overflow-y-auto">
        <div>
          <h2 className="text-2xl font-tech text-white mb-1 flex items-center gap-2">
            <Sparkles className="w-6 h-6 text-cyan-400" /> Command Center
          </h2>
          <p className="text-slate-400 text-sm">Orchestrate multi-channel campaigns with a single directive.</p>
        </div>

        <div className="space-y-6">
          <div>
            <label className="block text-xs font-mono text-slate-500 uppercase mb-2">Campaign Objective</label>
            <textarea
              value={objective}
              onChange={(e) => setObjective(e.target.value)}
              placeholder="e.g., Announce our new partnership..."
              className="w-full bg-slate-900/50 border border-slate-700 rounded-xl p-4 text-slate-200 focus:outline-none focus:border-cyan-500/50 focus:ring-1 focus:ring-cyan-500/20 h-40 resize-none"
            />
          </div>

          <div>
            <label className="block text-xs font-mono text-slate-500 uppercase mb-2">Target Audience</label>
            <input
              type="text"
              value={audienceOverride}
              onChange={(e) => setAudienceOverride(e.target.value)}
              placeholder={brand.audience || "Default Brand Audience"}
              className="w-full bg-slate-900/50 border border-slate-700 rounded-xl p-3 text-slate-200 focus:outline-none"
            />
          </div>

          <div
            onClick={() => setUseSearch(!useSearch)}
            className={`p-4 rounded-xl border cursor-pointer transition-all flex items-start gap-3 ${useSearch ? 'bg-indigo-900/30 border-indigo-500/50' : 'bg-slate-800/30 border-slate-700/50'}`}
          >
            <Globe className={`w-5 h-5 mt-0.5 ${useSearch ? 'text-indigo-400' : 'text-slate-500'}`} />
            <div>
              <div className={`text-sm font-bold ${useSearch ? 'text-indigo-200' : 'text-slate-400'}`}>Enrich with Market Data</div>
              <div className="text-xs text-slate-500 mt-1">Uses Google Search to ground the campaign in real-time trends.</div>
            </div>
          </div>
        </div>

        <div className="mt-auto pt-4">
          <button
            onClick={handleGenerate}
            disabled={isGenerating || !objective}
            className="w-full py-4 bg-gradient-to-r from-cyan-600 to-blue-600 rounded-xl font-bold text-white tracking-wide shadow-[0_0_20px_rgba(8,145,178,0.4)] hover:shadow-[0_0_30px_rgba(8,145,178,0.6)] hover:scale-[1.02] transition-all disabled:opacity-50 disabled:cursor-not-allowed flex items-center justify-center gap-2"
          >
            {isGenerating ? (
              <><Loader2 className="w-5 h-5 animate-spin" /> SYNCHRONIZING AGENTS...</>
            ) : (
              <><SendIcon className="w-5 h-5" /> LAUNCH CAMPAIGN</>
            )}
          </button>
        </div>
      </div>

      {/* Output Hologram */}
      <div className="lg:col-span-8 glass-panel rounded-2xl border-t border-purple-500/20 flex flex-col relative overflow-hidden h-full">
        {!channels && !isGenerating && (
          <div className="absolute inset-0 flex flex-col items-center justify-center text-slate-600">
            <div className="w-32 h-32 rounded-full border border-dashed border-slate-700 animate-[spin_20s_linear_infinite] flex items-center justify-center">
              <div className="w-24 h-24 rounded-full border border-dashed border-slate-800 animate-[spin_10s_linear_reverse_infinite]" />
            </div>
            <p className="mt-8 font-mono text-xs uppercase tracking-widest text-slate-500">Awaiting Mission Parameters</p>
          </div>
        )}

        {isGenerating && (
          <div className="absolute inset-0 flex flex-col items-center justify-center bg-slate-900/50 backdrop-blur-sm z-10">
            <div className="font-mono text-cyan-400 mb-2">GENERATING MULTI-CHANNEL ASSETS...</div>
            <div className="w-64 h-1 bg-slate-800 rounded-full overflow-hidden">
              <div className="h-full bg-cyan-500 animate-[progress_2s_ease-in-out_infinite]" />
            </div>
          </div>
        )}

        {channels && (
          <div className="flex flex-col h-full animate-in fade-in zoom-in-95 duration-500">

            {/* Score Header */}
            <div className="p-6 border-b border-slate-700/50 flex justify-between items-center bg-slate-900/30">
              <div>
                <h3 className="text-lg font-bold text-white">Campaign Output</h3>
                <div className="text-xs text-slate-400">{channels.length} Channels • AI Optimized</div>
              </div>
              {consistencyScore !== null && (
                <div className="flex items-center gap-3">
                  <div className="text-right">
                    <div className="text-[10px] uppercase text-slate-500">Brand Score</div>
                    <div className={`text-xl font-bold ${consistencyScore > 80 ? 'text-green-400' : 'text-yellow-400'}`}>{consistencyScore}%</div>
                  </div>
                  <div className="w-10 h-10 rounded-full border-2 border-slate-700 flex items-center justify-center">
                    <CheckCircle2 className={`w-5 h-5 ${consistencyScore > 80 ? 'text-green-400' : 'text-yellow-400'}`} />
                  </div>
                </div>
              )}
            </div>

            {/* Research Summary */}
            {researchResult && (
              <div className="bg-indigo-950/30 border-b border-indigo-500/20 px-6 py-3">
                <div className="flex items-center gap-2 text-indigo-300 text-xs font-bold uppercase mb-1">
                  <Globe className="w-3 h-3" /> Market Intelligence Found
                </div>
                <div className="flex gap-4 overflow-x-auto pb-1">
                  {researchResult.sources.slice(0, 3).map((s, i) => (
                    <a key={i} href={s.uri} target="_blank" rel="noreferrer" className="text-[10px] text-indigo-400 hover:underline truncate max-w-[200px] flex-shrink-0">
                      {s.title}
                    </a>
                  ))}
                </div>
              </div>
            )}

            {/* Tabs */}
            <div className="flex border-b border-slate-700/50 px-6 gap-6 overflow-x-auto">
              {channels.map((channel, idx) => (
                <button
                  key={channel.platform}
                  onClick={() => handleTabChange(idx)}
                  className={`py-4 text-sm font-medium flex items-center gap-2 border-b-2 transition-colors ${activeTab === idx
                    ? 'border-cyan-400 text-cyan-400'
                    : 'border-transparent text-slate-500 hover:text-slate-300'
                    }`}
                >
                  {getIcon(channel.platform)}
                  <span className="uppercase">{channel.platform}</span>
                </button>
              ))}
            </div>

            {/* Content Body */}
            <div className="flex-1 p-8 overflow-y-auto">
              <div className="max-w-3xl mx-auto space-y-6">

                {/* Platform Preview Mockup */}
                <div className="bg-white text-black rounded-xl overflow-hidden shadow-2xl max-w-lg mx-auto">
                  {/* Header Mockup */}
                  <div className="bg-slate-100 p-3 border-b border-slate-200 flex items-center gap-2">
                    <div className="w-8 h-8 rounded-full bg-slate-300" />
                    <div>
                      <div className="text-xs font-bold">{brand.name}</div>
                      <div className="text-[10px] text-slate-500">Just now • {channels[activeTab].platform}</div>
                    </div>

                    {/* Share Buttons */}
                    <div className="ml-auto flex gap-1">
                      <button onClick={() => handleShare('twitter')} title="Share to Twitter" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-blue-400">
                        <Twitter className="w-3 h-3" />
                      </button>
                      <button onClick={() => handleShare('facebook')} title="Share to Facebook" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-blue-600">
                        <Facebook className="w-3 h-3" />
                      </button>
                      <button onClick={() => handleShare('linkedin')} title="Share to LinkedIn" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-blue-700">
                        <Linkedin className="w-3 h-3" />
                      </button>
                      <button onClick={() => handleShare('whatsapp')} title="Share to WhatsApp" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-green-500">
                        <MessageCircle className="w-3 h-3" />
                      </button>
                      <button onClick={() => handleShare('telegram')} title="Share to Telegram" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-sky-500">
                        <Send className="w-3 h-3" />
                      </button>
                      <button onClick={() => handleShare('email')} title="Share via Email" className="p-1.5 hover:bg-slate-200 rounded text-slate-500 hover:text-orange-500">
                        <Mail className="w-3 h-3" />
                      </button>
                    </div>
                  </div>

                  {/* Content */}
                  <div className="p-5">
                    {channels[activeTab].headline && (
                      <h4 className="font-bold text-lg mb-2">{channels[activeTab].headline}</h4>
                    )}
                    <p className="text-sm whitespace-pre-wrap leading-relaxed">{channels[activeTab].content}</p>

                    {channels[activeTab].hashtags && (
                      <div className="mt-3 text-blue-600 text-xs">
                        {channels[activeTab].hashtags?.map(t => `#${t} `)}
                      </div>
                    )}

                    {/* Image Section */}
                    {!channels[activeTab].generatedImage && (
                      <div className="mt-4 bg-slate-100 rounded-lg p-4 border-2 border-dashed border-slate-300">
                        <div className="flex items-center justify-between mb-2">
                          <div className="flex items-center gap-2 text-slate-500">
                            <ImageIcon className="w-4 h-4" />
                            <span className="text-xs font-bold uppercase">AI Image Generator</span>
                          </div>
                          <button
                            onClick={() => {
                              const newMode = !isThumbnailMode;
                              setIsThumbnailMode(newMode);
                              if (newMode) setImageRatio("16:9");
                            }}
                            className={`flex items-center gap-1 px-2 py-1 rounded text-[10px] font-bold uppercase transition-all border ${isThumbnailMode ? 'bg-red-500/10 text-red-500 border-red-500/20' : 'bg-slate-200 text-slate-500 border-transparent hover:bg-slate-300'}`}
                          >
                            <MonitorPlay className="w-3 h-3" />
                            {isThumbnailMode ? 'Thumbnail Mode ON' : 'Generate Thumbnail'}
                          </button>
                        </div>

                        <div className="mb-3">
                          <label className="text-[10px] uppercase text-slate-400 font-bold mb-1 block">Image Prompt</label>
                          <textarea
                            value={customImagePrompt}
                            onChange={(e) => setCustomImagePrompt(e.target.value)}
                            className="w-full bg-white border border-slate-300 rounded p-2 text-xs text-slate-700 h-20 focus:outline-none focus:border-purple-500 resize-none"
                            placeholder="Describe the image you want to generate..."
                          />
                        </div>

                        <div className="grid grid-cols-2 gap-2 mb-4">
                          <div className="space-y-1">
                            <label className="text-[10px] uppercase text-slate-400 font-bold">Ratio</label>
                            <select value={imageRatio} onChange={e => setImageRatio(e.target.value)} className="w-full bg-white border border-slate-300 text-xs p-1.5 rounded focus:outline-none">
                              {["1:1", "16:9", "9:16", "4:3", "3:4"].map(r => <option key={r} value={r}>{r}</option>)}
                            </select>
                          </div>
                          <div className="space-y-1">
                            <label className="text-[10px] uppercase text-slate-400 font-bold">Size</label>
                            <select value={imageSize} onChange={e => setImageSize(e.target.value)} className="w-full bg-white border border-slate-300 text-xs p-1.5 rounded focus:outline-none">
                              {["1K", "2K", "4K"].map(s => <option key={s} value={s}>{s}</option>)}
                            </select>
                          </div>
                          <div className="col-span-2 space-y-1">
                            <label className="text-[10px] uppercase text-slate-400 font-bold">Style</label>
                            <select value={imageStyle} onChange={e => setImageStyle(e.target.value)} className="w-full bg-white border border-slate-300 text-xs p-1.5 rounded focus:outline-none">
                              {["Photorealistic", "Cyberpunk", "Cinematic", "Minimalist", "Studio Lighting", "Anime", "Vintage", "Neon", "Abstract", "Oil Painting", "3D Render"].map(s => <option key={s} value={s}>{s}</option>)}
                            </select>
                          </div>
                        </div>

                        <button
                          onClick={() => handleGenerateImage(customImagePrompt)}
                          disabled={isGeneratingImage || !customImagePrompt}
                          className={`w-full py-2 text-white rounded text-xs font-bold flex items-center justify-center gap-2 transition-colors disabled:opacity-50 ${isThumbnailMode ? 'bg-red-600 hover:bg-red-500' : 'bg-purple-600 hover:bg-purple-500'}`}
                        >
                          {isGeneratingImage ? <Loader2 className="w-3 h-3 animate-spin" /> : (isThumbnailMode ? <MonitorPlay className="w-3 h-3" /> : <Sparkles className="w-3 h-3" />)}
                          {isThumbnailMode ? 'GENERATE THUMBNAIL' : 'GENERATE IMAGE (Nano Banana)'}
                        </button>
                      </div>
                    )}

                    {channels[activeTab].generatedImage && (
                      <div className="mt-4 group relative">
                        <img src={channels[activeTab].generatedImage} alt="Generated" className="w-full rounded-lg" />
                        <div className="mt-2 bg-slate-100 p-3 rounded-lg border border-slate-200">
                          <div className="text-[10px] uppercase font-bold text-slate-500 mb-1 flex items-center gap-1">
                            <Wand2 className="w-3 h-3" /> Magic Editor
                          </div>
                          <div className="flex gap-2">
                            <input
                              type="text"
                              value={editPrompt}
                              onChange={(e) => setEditPrompt(e.target.value)}
                              placeholder="e.g. Add a retro filter..."
                              className="flex-1 bg-white border border-slate-300 rounded px-2 py-1 text-xs"
                            />
                            <button
                              onClick={handleEditImage}
                              disabled={isEditingImage || !editPrompt}
                              className="bg-slate-800 text-white px-3 py-1 rounded text-xs hover:bg-slate-700"
                            >
                              {isEditingImage ? <Loader2 className="w-3 h-3 animate-spin" /> : "Apply"}
                            </button>
                          </div>
                        </div>
                      </div>
                    )}

                  </div>

                  {/* Action Bar Mockup */}
                  <div className="bg-slate-50 p-3 border-t border-slate-200 flex justify-between text-slate-400">
                    <div className="w-4 h-4 rounded bg-slate-300" />
                    <div className="w-4 h-4 rounded bg-slate-300" />
                    <div className="w-4 h-4 rounded bg-slate-300" />
                  </div>
                </div>

              </div>
            </div>

            {/* Footer Actions */}
            <div className="p-6 border-t border-slate-700/50 flex flex-col gap-4 bg-slate-900/30">

              {/* Row 1: Localization & Scheduling */}
              <div className="flex gap-4">
                {/* Translation */}
                <div className="flex-1 flex gap-2">
                  <div className="relative flex-1">
                    <select
                      value={targetLang}
                      onChange={(e) => setTargetLang(e.target.value)}
                      disabled={isTranslating}
                      className="w-full h-full bg-slate-800 border border-slate-700 rounded-lg text-xs px-3 pl-8 appearance-none focus:outline-none focus:border-cyan-500 text-slate-300"
                    >
                      <option>English</option>
                      <option>Spanish</option>
                      <option>French</option>
                      <option>German</option>
                      <option>Chinese (Simplified)</option>
                      <option>Japanese</option>
                      <option>Portuguese</option>
                      <option>Italian</option>
                      <option>Arabic</option>
                      <option>Russian</option>
                      <option>Korean</option>
                      <option>Hindi</option>
                    </select>
                    <Languages className="absolute left-3 top-1/2 -translate-y-1/2 w-3 h-3 text-slate-500 pointer-events-none" />
                  </div>
                  <button
                    onClick={handleTranslate}
                    disabled={isTranslating || targetLang === 'English'}
                    className="px-3 bg-slate-700 hover:bg-slate-600 rounded-lg text-xs font-bold text-white transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
                  >
                    {isTranslating ? <Loader2 className="w-4 h-4 animate-spin" /> : 'Translate'}
                  </button>
                </div>

                {/* Scheduling Input */}
                <div className="flex-1 relative">
                  <div className="absolute inset-y-0 left-3 flex items-center pointer-events-none">
                    <Calendar className="w-3 h-3 text-slate-500" />
                  </div>
                  <input
                    type="datetime-local"
                    value={scheduledDate}
                    onChange={(e) => setScheduledDate(e.target.value)}
                    className="w-full h-full bg-slate-800 border border-slate-700 rounded-lg text-xs pl-9 pr-3 focus:outline-none focus:border-cyan-500 text-slate-300 placeholder-slate-500"
                    placeholder="Schedule Post"
                  />
                </div>
              </div>

              {/* Row 2: Actions */}
              <div className="flex gap-4">
                <button
                  onClick={handleCopy}
                  className={`flex-1 py-3 rounded-lg font-medium transition-colors flex items-center justify-center gap-2 ${copied ? 'bg-green-600 text-white' : 'bg-slate-800 hover:bg-slate-700 text-white'}`}
                >
                  {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
                  {copied ? 'Copied' : 'Copy Text'}
                </button>
                <button
                  onClick={handlePush}
                  disabled={pushed || pushLoading}
                  className="flex-1 py-3 bg-cyan-600 hover:bg-cyan-500 rounded-lg text-white font-bold transition-colors shadow-lg shadow-cyan-500/20 flex items-center justify-center gap-2 disabled:opacity-70 disabled:cursor-not-allowed"
                >
                  {pushLoading ? <Loader2 className="w-4 h-4 animate-spin" /> : <SendIcon className="w-4 h-4" />}
                  {pushed ? 'Pushed' : (scheduledDate ? 'Schedule & Push' : 'Push to Automation')}
                </button>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};

export default Generator;
